#!/usr/bin/env python3
"""Generate native UI data from export_native_encounter_library.php output."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

HEADER = "-- Generated by tools/generate_native_encounter_library.py from the public Bastion Library export.\n"
INDEX_FIELDS = ("slug", "title", "zone", "zoneShortName", "zoneVersion", "group", "kind", "summary")
DETAIL_FIELDS = ("overview", "roles", "phases", "abilities", "sections")
ROW_FIELDS = {
    "roles": ("id", "label", "tips"),
    "phases": ("label", "trigger", "description"),
    "abilities": ("name", "summary", "description", "tags", "roles"),
    "sections": ("title", "paragraphs", "bullets"),
}
TEXT_LIST_FIELDS = {"tips", "tags", "roles", "paragraphs", "bullets"}
CHUNK_BYTES = 64 * 1024
LUA_IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
GUIDE_SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
CHUNK_FILENAME = re.compile(r"detail_[0-9]+\.lua")


def quote(text: str) -> str:
    escapes = {'"': '\\"', "\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    return '"' + "".join(
        escapes.get(char, f"\\{ord(char):03d}" if ord(char) < 32 or ord(char) == 127 else char)
        for char in text
    ) + '"'


def lua(value) -> str:
    if isinstance(value, str):
        return quote(value)
    if type(value) is int:
        return str(value)
    if isinstance(value, list):
        return "{" + ", ".join(map(lua, value)) + "}"
    if isinstance(value, dict):
        fields = (
            f"{key if LUA_IDENTIFIER.fullmatch(key) else '[' + quote(key) + ']'} = {lua(item)}"
            for key, item in value.items()
        )
        return "{" + ", ".join(fields) + "}"
    raise ValueError(f"Unsupported native catalog value {type(value).__name__}")


def text_list(value) -> bool:
    return isinstance(value, list) and all(isinstance(line, str) for line in value)


def detail_rows(section: str, rows) -> list:
    if not isinstance(rows, list):
        raise ValueError(f"{section} must be a list")
    fields = ROW_FIELDS[section]
    projected = []
    for row in rows:
        if not isinstance(row, dict) or row.keys() != set(fields):
            raise ValueError(f"Unexpected fields in {section}")
        for key, value in row.items():
            is_list = key in TEXT_LIST_FIELDS or (section == "abilities" and key == "description")
            if not (text_list(value) if is_list else isinstance(value, str)):
                raise ValueError(f"Invalid {section} value for {key}")
        projected.append({key: row[key] for key in fields})
    return projected


def bundle(export: dict) -> dict[str, str]:
    guides = export.get("guides")
    if export.get("version") != 1 or not isinstance(guides, list) or not guides:
        raise ValueError("Expected a nonempty version 1 public encounter export")
    index = []
    chunks = [[]]
    chunk_size = 0
    known = set()
    for guide in guides:
        if not isinstance(guide, dict) or guide.keys() != set(INDEX_FIELDS + DETAIL_FIELDS):
            raise ValueError("Unexpected fields in native encounter guide")
        for key in (field for field in INDEX_FIELDS if field != "zoneVersion"):
            if not isinstance(guide[key], str) or not guide[key]:
                raise ValueError(f"Missing guide {key}")
        slug = guide["slug"]
        if slug in known or not GUIDE_SLUG.fullmatch(slug):
            raise ValueError(f"Duplicate or invalid guide slug: {slug}")
        if type(guide["zoneVersion"]) is not int or guide["zoneVersion"] < 0:
            raise ValueError(f"Invalid zone version for {slug}")
        known.add(slug)
        if not text_list(guide["overview"]):
            raise ValueError(f"Invalid overview for {slug}")
        detail = {"overview": guide["overview"]}
        for key in ROW_FIELDS:
            detail[key] = detail_rows(key, guide[key])
        line = f"  [{quote(slug)}] = {lua(detail)},\n"
        size = len(line.encode("utf-8"))
        if size > CHUNK_BYTES:
            raise ValueError(f"Guide details exceed a native chunk: {slug}")
        if chunk_size + size > CHUNK_BYTES:
            chunks.append([])
            chunk_size = 0
        chunks[-1].append(line)
        chunk_size += size
        row = {key: guide[key] for key in INDEX_FIELDS}
        row["detailFile"] = f"lib/encounter_library/detail_{len(chunks):02d}.lua"
        index.append("  " + lua(row) + ",\n")

    files = {"encounter_library_index.lua": HEADER + "return {\n" + "".join(index) + "}\n"}
    files.update({
        f"encounter_library/detail_{number:02d}.lua": HEADER + "return {\n" + "".join(lines) + "}\n"
        for number, lines in enumerate(chunks, 1)
    })
    return files


def apply(bundle_files: dict[str, str], pack: Path, check: bool) -> None:
    root = pack / "lib"
    chunks = root / "encounter_library"
    if chunks.is_symlink():
        raise ValueError(f"Refusing to update a linked catalog directory: {chunks}")
    stale = [
        path for path in chunks.glob("detail_*.lua")
        if CHUNK_FILENAME.fullmatch(path.name) and f"encounter_library/{path.name}" not in bundle_files
    ]
    for path in stale + [root / name for name in bundle_files]:
        if path.is_symlink() or (path.exists() and not path.read_bytes().startswith(HEADER.encode("utf-8"))):
            raise ValueError(f"Refusing to overwrite a file outside the generated catalog: {path}")
    if check:
        expected = all(
            (root / name).is_file() and (root / name).read_bytes() == contents.encode("utf-8")
            for name, contents in bundle_files.items()
        )
        if stale or not expected:
            raise ValueError(f"Generated encounter catalog is out of date for {pack.name}")
        return
    chunks.mkdir(parents=True, exist_ok=True)
    for name, contents in bundle_files.items():
        (root / name).write_bytes(contents.encode("utf-8"))
    for path in stale:
        path.unlink()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("export", type=Path, help="Public JSON from export_native_encounter_library.php")
    parser.add_argument("--check", action="store_true", help="Verify both generated UI packs without changing them")
    args = parser.parse_args()
    data = json.loads(args.export.read_text(encoding="utf-8"))
    files = bundle(data)
    root = Path(__file__).resolve().parents[1]
    for pack in ("modern", "gamepad"):
        apply(files, root / "ui" / pack, args.check)
    print(f"{len(data['guides'])} public guides in {len(files) - 1} native detail chunks")


if __name__ == "__main__":
    main()
