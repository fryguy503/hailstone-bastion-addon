#!/usr/bin/env python3
"""Generate the offline guide from Bastion Library's public expedition export."""
import argparse
import json
from pathlib import Path


def lua(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def render(catalog: dict) -> str:
    if catalog["version"] != 1 or catalog["id"] != "mistmoore-eclipse":
        raise ValueError("Expected the Mistmoore Eclipse version 1 catalog")
    lines = ["-- Generated by tools/update_journal_catalog.py from the Bastion Library export.", "return {"]
    for key in ("normal", "bloodbound", "vigil"):
        mode = catalog["modes"][key]
        unlock = mode["unlock"]
        entry = catalog["entry"]
        keywords = " or ".join(mode["requestKeywords"])
        first_step = f"Say {keywords} to request."
        if unlock["kind"] == "relics":
            first_step = f"Unlock first, then say {keywords} on later runs."
        location = f"{entry['name']} · {entry['location']}. {first_step} Say {mode['enterKeyword']} to enter."
        rules = (
            f"{mode['minRoster']}–{mode['maxRoster']} characters · {mode['tunedFor']} · "
            f"{mode['instanceSeconds'] // 3600}h run · {mode['replaySeconds'] // 3600}h replay"
        )
        items = ", ".join(item["name"] for item in unlock["items"])
        requirements = {
            "relics": f"First Normal request: the raid leader hands over all four relics together ({items}).",
            "writ": f"Bloodbound requires the requester's permanent unlock. Redeem one {items}.",
            "none": "The group leader requests this expedition, which supplies the Normal raid relics.",
        }
        guide = mode["guide"]
        title = guide[0]["title"] if key == "vigil" else catalog["title"]
        lines.extend((
            "  {",
            f"    name = {lua(mode['label'])},",
            f"    title = {lua(title)},",
            f"    entry = {lua(location)},",
            f"    rules = {lua(rules)},",
            f"    unlock = {lua(requirements[unlock['kind']])},",
            "    encounters = {",
        ))
        for encounter in guide:
            lines.append(f"      {{{lua(encounter['title'])}, {lua(encounter['summary'])}}},")
        lines.extend(("    },", "  },"))
    lines.extend(("}", ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("export", type=Path, help="JSON from /library/api/v1/expeditions/mistmoore-eclipse")
    args = parser.parse_args()
    content = render(json.loads(args.export.read_text(encoding="utf-8")))
    root = Path(__file__).resolve().parents[1]
    for pack in ("modern", "gamepad"):
        (root / "ui" / pack / "lib" / "expedition_journal_catalog.lua").write_text(
            content, encoding="utf-8", newline="\n"
        )


if __name__ == "__main__":
    main()
